export function getLang(navLang?: string): Lang {
  const l = navLang ?? (typeof navigator !== 'undefined' ? (navigator.language || '') : '');
  return l.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

export function t(lang?: Lang): (typeof translations)[Lang] {
  const resolved = lang ?? getLang();
  return translations[resolved];
}
